export async function seedUser(db: D1Database, owner: string) {
  const t = Date.now()
  const statements: D1PreparedStatement[] = []

  decks.forEach((deck, di) => {
    const deckId = id()
    const lastStudied = di === 0 ? t - 3 * 3_600_000 : di === 1 ? t - 1.2 * DAY : t - 6 * DAY
    statements.push(
      db
        .prepare(`INSERT INTO decks (id, owner_sub, title, description, hue, last_studied_at, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)`)
        .bind(deckId, owner, deck.title, deck.description, hueFor(deck.title), lastStudied, t - (20 - di * 4) * DAY, lastStudied),
    )
    deck.cards.forEach(([term, definition], ci) => {
      const cardId = id()
      statements.push(
        db
          .prepare(`INSERT INTO cards (id, owner_sub, deck_id, term, definition, position, created_at) VALUES (?, ?, ?, ?, ?, ?, ?)`)
          .bind(cardId, owner, deckId, term, definition, ci, t - (20 - di * 4) * DAY + ci),
      )
      // Fresh seed: no card progress, so a new account starts at 0% across the
      // deck list until the user actually reviews a card. last_studied_at on
      // decks is kept so the library opens in a sensible order without
      // fabricating any streak, XP or session history.
    })
  })

  statements.push(db.prepare(`UPDATE users SET seeded_at = ?, seed_version = ? WHERE owner_sub = ?`).bind(t, SEED_VERSION, owner))
  for (let i = 0; i < statements.length; i += 40) await db.batch(statements.slice(i, i + 40))
}

/**
 * Adds starter decks that an existing account predates, matched by title so a
 * re-run never duplicates a deck the user already has (or edited away).
 */
export async function topUpUser(db: D1Database, owner: string) {
  const existing = await db.prepare(`SELECT LOWER(title) AS title FROM decks WHERE owner_sub = ?`).bind(owner).all<{ title: string }>()
  const have = new Set(existing.results.map((row) => row.title))
  const t = Date.now()
  const statements: D1PreparedStatement[] = []

  for (const deck of decks) {
    if (have.has(deck.title.toLowerCase())) continue
    const deckId = id()
    statements.push(
      db
        .prepare(`INSERT INTO decks (id, owner_sub, title, description, hue, last_studied_at, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)`)
        .bind(deckId, owner, deck.title, deck.description, hueFor(deck.title), null, t, t),
    )
    deck.cards.forEach(([term, definition], ci) => {
      statements.push(
        db
          .prepare(`INSERT INTO cards (id, owner_sub, deck_id, term, definition, position, created_at) VALUES (?, ?, ?, ?, ?, ?, ?)`)
          .bind(id(), owner, deckId, term, definition, ci, t + ci),
      )
    })
  }

  statements.push(db.prepare(`UPDATE users SET seed_version = ? WHERE owner_sub = ?`).bind(SEED_VERSION, owner))
  for (let i = 0; i < statements.length; i += 40) await db.batch(statements.slice(i, i + 40))
}

export async function clearUser(db: D1Database, owner: string) {
  await db.batch(['sessions', 'card_progress', 'cards', 'decks'].map((table) => db.prepare(`DELETE FROM ${table} WHERE owner_sub = ?`).bind(owner)))
  await db.prepare(`UPDATE users SET seeded_at = NULL, seed_version = 0 WHERE owner_sub = ?`).bind(owner).run()
}
